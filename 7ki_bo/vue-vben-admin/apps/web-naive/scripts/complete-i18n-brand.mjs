function processFile(rel, reps) {
  const fp = path.join(brandDir, rel);
  let c = fs.readFileSync(fp, 'utf8');
  if (!c.includes("from '@vben/locales'")) {
    c = c.replace(/import \{ /, "import { $t } from '@vben/locales';\n\nimport { ");
  }
  for (const [a, b] of reps) c = c.replace(a, b);
  c = c.replace(/(import \{ \$t \} from '@vben\/locales';\n\n)+/g, "import { $t } from '@vben/locales';\n\n");
  fs.writeFileSync(fp, c);
  console.log('brand updated', rel);
}

