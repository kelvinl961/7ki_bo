function walkDir(d, a = []) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const f = path.join(d, e.name);
    if (e.isDirectory()) walkDir(f, a);
    else if (f.endsWith('.vue')) a.push(f);
  }
  return a;
}

function getNested(obj, keyPath) {
  return keyPath.split('.').reduce((o, k) => o?.[k], obj);
}

const zhA = readJson(path.join(localesDir, 'zh-CN/activity.json'));
const activity = readJson(path.join(localesDir, 'vi-VN/activity.json'));
const used = new Set();
for (const f of [...walkDir(path.join(__dirname, '../src/views/activity')), ...walkDir(path.join(__dirname, '../src/views/user'))]) {
  const s = fs.readFileSync(f, 'utf8');
  let m;
  const re = /\$t\(['"]activity\.([^'"]+)/g;
  while ((m = re.exec(s))) used.add(m[1]);
}

let fixed = 0;
let still = 0;
for (const k of used) {
  const zh = getNested(zhA, k);
  const cur = getNested(activity, k);
  if (typeof zh !== 'string' || !hasChinese(zh)) continue;
  if (typeof cur === 'string' && !hasChinese(cur) && !/\b(Please|Activity|Reward|Select|Enter|Failed|Loading)\b/i.test(cur)) continue;
  const vi = translateZh(zh);
  if (vi && !hasChinese(vi)) {
    setNested(activity, k, vi);
    fixed++;
  } else {
    still++;
  }
}
writeJson(path.join(localesDir, 'vi-VN/activity.json'), activity);
console.log(`Fixed ${fixed}, still ${still}`);
