function translateByWords(zh) {
  if (ACTIVITY_VI[zh]) return ACTIVITY_VI[zh];
  let s = zh;
  for (const [cn, vi] of VI_WORDS) {
    if (s.includes(cn)) s = s.split(cn).join(vi);
  }
  s = s
    .replace(/，/g, ', ')
    .replace(/。/g, '.')
    .replace(/；/g, '; ')
    .replace(/：/g, ': ')
    .replace(/（/g, ' (')
    .replace(/）/g, ') ')
    .replace(/、/g, ', ')
    .replace(/\s+/g, ' ')
    .trim();
  if (hasChinese(s)) return null;
  return s;
}

