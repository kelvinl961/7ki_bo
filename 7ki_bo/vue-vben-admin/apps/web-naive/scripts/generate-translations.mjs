function translateToEn(zh) {
  if (EXPLICIT[zh]) return EXPLICIT[zh].en;
  if (ZH_WORDS[zh]) return ZH_WORDS[zh];

  // Try longest-match composition
  let remaining = zh;
  const parts = [];
  const sortedKeys = Object.keys(ZH_WORDS).sort((a, b) => b.length - a.length);
  while (remaining.length > 0) {
    let matched = false;
    for (const k of sortedKeys) {
      if (remaining.startsWith(k)) {
        const w = ZH_WORDS[k];
        if (w) parts.push(w);
        remaining = remaining.slice(k.length);
        matched = true;
        break;
      }
    }
    if (!matched) {
      // keep punctuation/numbers
      const m = remaining.match(/^[\s\d:：,，.。?？!！()（）\-_/\\]+/);
      if (m) {
        parts.push(m[0].trim());
        remaining = remaining.slice(m[0].length);
      } else {
        parts.push(remaining[0]);
        remaining = remaining.slice(1);
      }
    }
  }
  const en = parts.filter(Boolean).join(' ').replace(/\s+/g, ' ').trim();
  return en || zh;
}

function translateToVi(en) {
  const words = en.split(/\s+/);
  const vi = words
    .map((w) => VI_WORDS[w] || VI_WORDS[w.replace(/[^a-zA-Z]/g, '')] || w)
    .join(' ');
  return vi;
}

