export function getBrandColorTemplateBySlug(
  slug: string,
): BrandColorTemplate | undefined {
  return BRAND_COLOR_TEMPLATES.find((t) => t.id === slug);
}

export function getBrandColorTemplateByBackendId(
  backendSkinId: string,
): BrandColorTemplate | undefined {
  const slug = TEMPLATE_SLUG_BY_BACKEND_SKIN_ID[backendSkinId];
  return slug ? getBrandColorTemplateBySlug(slug) : undefined;
}

export function buildSkinColorOptions(): { value: string; label: string }[] {
  return BRAND_COLOR_TEMPLATES.map((t) => ({
    value: BACKEND_SKIN_ID_BY_TEMPLATE_SLUG[t.id] ?? '',
    label: t.label,
  })).filter((o) => o.value);
}
